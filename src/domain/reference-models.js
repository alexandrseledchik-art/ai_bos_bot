export function normalizeReferenceLayerKey(layerKey) {
  const normalized = String(layerKey || "").trim().toLowerCase();
  return LAYER_KEY_ALIASES[normalized] || normalized;
}

export function getReferenceModelTemplate(layerKey) {
  const key = normalizeReferenceLayerKey(layerKey);
  const template = REFERENCE_MODEL_TEMPLATES[key];
  const layer = getBusinessLayerByKey(key);

  if (!template || !layer) {
    return null;
  }

  return {
    ...template,
    layerTitle: layer.title,
    classKey: layer.classKey
  };
}
