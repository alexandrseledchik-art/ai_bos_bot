export const BUSINESS_LAYER_KEYS_V1 = BUSINESS_LAYERS_V1.map((layer) => layer.key);

export function getBusinessLayerByKey(layerKey) {
  return BUSINESS_LAYERS_V1.find((layer) => layer.key === layerKey) || null;
}

export function assertBusinessLayerKey(layerKey) {
  const layer = getBusinessLayerByKey(layerKey);
  if (!layer) {
    throw new Error(`Unknown business layer key: ${layerKey}`);
  }
  return layer;
}
