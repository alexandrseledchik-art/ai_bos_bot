function detectRequestedTool(text) {
  const normalized = normalizeText(text).toLowerCase();

  if (
    /\bbhag\b|\bбхаг\b|big\s+hairy\s+audacious\s+goal|больш[а-яё\s-]+амбициозн[а-яё\s-]+цел|дерзк[а-яё\s-]+цел/.test(
      normalized
    )
  ) {
    return {
      name: "BHAG",
      explanation: "большая дерзкая амбициозная цель: сильный ориентир на несколько лет, который тянет всю систему в одну сторону"
    };
  }
  if (/\braci\b|рас[иi]|матриц[ау]\s+ответственност|кто\s+.*чем\s+.*занима|роли?\s+и\s+ответственност|кто\s+за\s+что\s+отвеча/.test(normalized)) {
    return {
      name: "RACI",
      explanation: "матрица ответственности: кто делает, кто утверждает, кого нужно спросить и кого держать в курсе"
    };
  }
  if (/\bsipoc\b/.test(normalized)) {
    return {
      name: "SIPOC",
      explanation: "схема процесса: поставщики, входы, сам процесс, выходы и клиенты процесса"
    };
  }
  if (/\bswot\b/.test(normalized)) {
    return {
      name: "SWOT",
      explanation: "карта сильных и слабых сторон, возможностей и угроз"
    };
  }
  if (/\bjtbd\b|job\s+to\s+be\s+done/.test(normalized)) {
    return {
      name: "JTBD",
      explanation: "логика задачи клиента: ради какого прогресса он покупает продукт"
    };
  }
  if (/юнит-?экономик|unit\s+economics/.test(normalized)) {
    return {
      name: "юнит-экономика",
      explanation: "проверка, сколько бизнес зарабатывает и теряет на одной продаже или клиенте"
    };
  }

  return {
    name: "инструмент",
    explanation: "рабочий шаблон или схема, которая помогает принять решение, а не просто красиво оформить мысли"
  };
}

function detectRequestedToolFromContext(context) {
  const sources = [
    context.userText,
    context.entryState?.claimedProblem,
    ...((context.history || []).filter((item) => item.role === "user").map((item) => item.text))
  ];

  for (const source of sources) {
    const tool = detectRequestedTool(source);
    if (tool.name !== "инструмент") {
      return tool;
    }
  }

  return detectRequestedTool(context.userText);
}

function detectToolZone(text) {
  const normalized = normalizeText(text).toLowerCase();
  if (/продаж|лид|заяв|воронк|кп|сделк/.test(normalized)) {
    return "продажи";
  }
  if (/маркет|реклам|трафик|канал/.test(normalized)) {
    return "маркетинг";
  }
  if (/доставк|исполн|операц|процесс|производ/.test(normalized)) {
    return "исполнение";
  }
  if (/поддерж|сервис|клиентск/.test(normalized)) {
    return "поддержка";
  }
  if (/управл|решени|руковод|менеджмент/.test(normalized)) {
    return "управление";
  }
  return "";
}

function detectToolZoneFromContext(context) {
  const sources = [
    context.userText,
    context.entryState?.claimedProblem,
    ...((context.history || []).filter((item) => item.role === "user").map((item) => item.text))
  ];

  for (const source of sources) {
    const zone = detectToolZone(source);
    if (zone) {
      return zone;
    }
  }

  return "";
}

function isBhagTool(tool) {
  return normalizeText(tool?.name).toLowerCase() === "bhag";
}

function detectBhagContourFromContext(context) {
  const sources = [
    context.userText,
    context.entryState?.claimedProblem,
    ...((context.history || []).filter((item) => item.role === "user").map((item) => item.text))
  ];
  const normalized = normalizeText(sources.join(" ")).toLowerCase();

  if (/backwood\.store|backwood|бэквуд/.test(normalized)) {
    return "backwood.store";
  }
  if (/упаковк[а-яё\s-]+консалтинг|мой\s+консалтинг|наш\s+консалтинг|для\s+консалтинг/.test(normalized)) {
    return "упаковки консалтинга";
  }
  return "";
}

